#!/usr/bin/env python3
"""Generate Swift and Kotlin skin tokens from design/skins.json.

    python3 design/gen_skins.py          # validate contrast, then write both files
    python3 design/gen_skins.py --check  # validate and fail if generated files are stale

Stdlib only. The generated files are committed; CI runs --check so a palette edit
cannot ship on one platform only.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "design" / "skins.json"
SWIFT_OUT = ROOT / "HabiticaPomodoro" / "HabiticaPomodoro" / "SkinTokens.swift"
KOTLIN_OUT = ROOT / "HabiticaPomodoroAndroid" / "app" / "src" / "main" / "java" / "com" / "habitica" / "pomodoro" / "ui" / "theme" / "SkinTokens.kt"

COLOR_KEYS = ["background", "backgroundAlt", "surface", "subtle", "line", "ink", "muted",
              "accent", "accentSoft", "onAccent", "rest", "restSoft", "danger", "highlight"]
LAYOUTS = ["compact", "airy", "columns"]
DESIGNS = ["default", "serif", "rounded", "monospaced", "pixel"]
WEIGHTS = ["thin", "light", "regular", "medium", "semibold", "bold"]
RING_STYLES = ["smooth", "ticks", "segmented"]
CARD_BORDERS = ["none", "line", "ink"]

# (foreground, background, minimum ratio). Text pairs use WCAG AA 4.5; ink uses AAA 7.
CONTRAST_RULES = [
    ("ink", "background", 7.0), ("ink", "surface", 7.0), ("ink", "subtle", 7.0),
    ("muted", "background", 4.5), ("muted", "surface", 4.5), ("muted", "subtle", 4.5),
    ("accent", "background", 4.5), ("accent", "surface", 4.5), ("accent", "accentSoft", 4.5),
    ("onAccent", "accent", 4.5),
    ("rest", "surface", 4.5), ("rest", "restSoft", 4.5),
    ("danger", "surface", 4.5),
    ("highlight", "surface", 3.0),
]
GENERATED_HEADER = "Generated by design/gen_skins.py from design/skins.json. Do not edit by hand."


def luminance(hex_value: str) -> float:
    def channel(c: int) -> float:
        v = c / 255
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
    n = int(hex_value, 16)
    r, g, b = (n >> 16) & 0xFF, (n >> 8) & 0xFF, n & 0xFF
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def contrast(a: str, b: str) -> float:
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def validate(spec: dict) -> list:
    errors = []
    ids = [s["id"] for s in spec["skins"]]
    if len(ids) != len(set(ids)):
        errors.append("duplicate skin ids")
    for layout in LAYOUTS:
        if layout not in spec["layouts"]:
            errors.append(f"missing layout {layout}")
    for skin in spec["skins"]:
        sid = skin["id"]
        if skin["layout"] not in LAYOUTS:
            errors.append(f"{sid}: unknown layout {skin['layout']}")
        if skin["forcedScheme"] not in (None, "dark", "light"):
            errors.append(f"{sid}: forcedScheme must be null, dark or light")
        if skin["shape"]["cardBorder"] not in CARD_BORDERS:
            errors.append(f"{sid}: unknown cardBorder")
        if skin["shape"]["shadow"] not in spec["shadows"]:
            errors.append(f"{sid}: unknown shadow")
        for key in ("titleDesign", "timerDesign"):
            if skin["type"][key] not in DESIGNS:
                errors.append(f"{sid}: unknown {key}")
        if skin["type"]["titleDesign"] == "pixel":
            errors.append(f"{sid}: pixel glyphs only cover timer digits")
        for key in ("titleWeight", "timerWeight"):
            if skin["type"][key] not in WEIGHTS:
                errors.append(f"{sid}: unknown {key}")
        if skin["ring"]["style"] not in RING_STYLES:
            errors.append(f"{sid}: unknown ring style")
        for mode in ("light", "dark"):
            palette = skin[mode]
            missing = [k for k in COLOR_KEYS if k not in palette]
            if missing:
                errors.append(f"{sid}.{mode}: missing {missing}")
                continue
            for fg, bg, minimum in CONTRAST_RULES:
                ratio = contrast(palette[fg], palette[bg])
                if ratio < minimum:
                    errors.append(f"{sid}.{mode}: {fg}/{bg} contrast {ratio:.2f} < {minimum}")
    glyphs = spec["pixelGlyphs"]
    for ch, rows in glyphs["glyphs"].items():
        if len(rows) != glyphs["height"] or len({len(r) for r in rows}) != 1 or any(set(r) - {"0", "1"} for r in rows):
            errors.append(f"pixel glyph {ch!r} must be {glyphs['height']} equal-width rows of 0/1")
    return errors


def swift_source(spec: dict) -> str:
    out = [f"// {GENERATED_HEADER}", "import CoreGraphics", ""]
    out += [
        "enum SkinLayout: String { case compact, airy, columns }",
        "enum SkinFontDesign: String { case `default`, serif, rounded, monospaced, pixel }",
        "enum SkinFontWeight: String { case thin, light, regular, medium, semibold, bold }",
        "enum SkinRingStyle: String { case smooth, ticks, segmented }",
        "enum SkinCardBorder: String { case none, line, ink }",
        "enum SkinShadowColor: String { case ink, accent }",
        "enum SkinForcedScheme: String { case light, dark }",
        "",
        "struct SkinPaletteTokens {",
    ]
    out += [f"    let {k}: UInt32" for k in COLOR_KEYS]
    out += [
        "}",
        "",
        "struct SkinShadowTokens { let radius: CGFloat; let x: CGFloat; let y: CGFloat; let opacity: Double; let color: SkinShadowColor }",
        "",
        "struct SkinLayoutTokens { let pageInset: CGFloat; let pageSpacing: CGFloat; let cardPadding: CGFloat; let rowSpacing: CGFloat; let macWindow: CGSize }",
        "",
        "struct SkinTokens {",
        "    let id: String",
        "    let title: String",
        "    let tagline: String",
        "    let symbol: String",
        "    let layout: SkinLayout",
        "    let forcedScheme: SkinForcedScheme?",
        "    let cardRadius: CGFloat",
        "    let controlRadius: CGFloat",
        "    let borderWidth: CGFloat",
        "    let cardBorder: SkinCardBorder",
        "    let shadow: SkinShadowTokens",
        "    let titleDesign: SkinFontDesign",
        "    let titleWeight: SkinFontWeight",
        "    let timerDesign: SkinFontDesign",
        "    let timerWeight: SkinFontWeight",
        "    let ringStyle: SkinRingStyle",
        "    let ringWidth: CGFloat",
        "    let ringKnob: Bool",
        "    let ringGlow: Bool",
        "    let light: SkinPaletteTokens",
        "    let dark: SkinPaletteTokens",
        "}",
        "",
        "enum SkinCatalog {",
        "    static let layouts: [SkinLayout: SkinLayoutTokens] = [",
    ]
    for name in LAYOUTS:
        l = spec["layouts"][name]
        out.append(f"        .{name}: SkinLayoutTokens(pageInset: {l['pageInset']}, pageSpacing: {l['pageSpacing']}, "
                   f"cardPadding: {l['cardPadding']}, rowSpacing: {l['rowSpacing']}, "
                   f"macWindow: CGSize(width: {l['macWindow'][0]}, height: {l['macWindow'][1]})),")
    out += ["    ]", "", "    /// Picker order.", "    static let all: [SkinTokens] = ["]

    def palette(p: dict) -> str:
        return "SkinPaletteTokens(" + ", ".join(f"{k}: 0x{p[k].upper()}" for k in COLOR_KEYS) + ")"

    for s in spec["skins"]:
        sh = spec["shadows"][s["shape"]["shadow"]]
        forced = f".{s['forcedScheme']}" if s["forcedScheme"] else "nil"
        out += [
            "        SkinTokens(",
            f"            id: \"{s['id']}\", title: \"{s['title']}\", tagline: \"{s['tagline']}\", symbol: \"{s['symbol']}\",",
            f"            layout: .{s['layout']}, forcedScheme: {forced},",
            f"            cardRadius: {s['shape']['cardRadius']}, controlRadius: {s['shape']['controlRadius']}, "
            f"borderWidth: {s['shape']['borderWidth']}, cardBorder: .{s['shape']['cardBorder']},",
            f"            shadow: SkinShadowTokens(radius: {sh['radius']}, x: {sh['x']}, y: {sh['y']}, opacity: {sh['opacity']}, color: .{sh['color']}),",
            f"            titleDesign: .{s['type']['titleDesign']}, titleWeight: .{s['type']['titleWeight']}, "
            f"timerDesign: .{s['type']['timerDesign']}, timerWeight: .{s['type']['timerWeight']},",
            f"            ringStyle: .{s['ring']['style']}, ringWidth: {s['ring']['width']}, "
            f"ringKnob: {str(s['ring']['knob']).lower()}, ringGlow: {str(s['ring']['glow']).lower()},",
            f"            light: {palette(s['light'])},",
            f"            dark: {palette(s['dark'])}",
            "        ),",
        ]
    glyphs = spec["pixelGlyphs"]
    out += ["    ]", "}", "", "/// 5x7 bitmap digits for the pixel timer; rows top to bottom, \"1\" = lit cell.", "enum PixelGlyphs {",
            f"    static let height = {glyphs['height']}", "    static let table: [Character: [String]] = ["]
    for ch, rows in glyphs["glyphs"].items():
        out.append(f"        \"{ch}\": [" + ", ".join(f"\"{r}\"" for r in rows) + "],")
    out += ["    ]", "}", ""]
    return "\n".join(out)


def kotlin_source(spec: dict) -> str:
    def enum_name(value: str) -> str:
        return value[0].upper() + value[1:]

    out = [f"// {GENERATED_HEADER}", "package com.habitica.pomodoro.ui.theme", ""]
    out += [
        "enum class SkinLayout { Compact, Airy, Columns }",
        "enum class SkinFontDesign { Default, Serif, Rounded, Monospaced, Pixel }",
        "enum class SkinFontWeight { Thin, Light, Regular, Medium, Semibold, Bold }",
        "enum class SkinRingStyle { Smooth, Ticks, Segmented }",
        "enum class SkinCardBorder { None, Line, Ink }",
        "enum class SkinShadowColor { Ink, Accent }",
        "enum class SkinForcedScheme { Light, Dark }",
        "",
        "data class SkinPaletteTokens(",
    ]
    out += [f"    val {k}: Long," for k in COLOR_KEYS]
    out += [
        ")",
        "",
        "data class SkinShadowTokens(val radius: Float, val x: Float, val y: Float, val opacity: Float, val color: SkinShadowColor)",
        "",
        "data class SkinLayoutTokens(val pageInset: Float, val pageSpacing: Float, val cardPadding: Float, val rowSpacing: Float)",
        "",
        "data class SkinTokens(",
        "    val id: String,",
        "    val title: String,",
        "    val tagline: String,",
        "    val layout: SkinLayout,",
        "    val forcedScheme: SkinForcedScheme?,",
        "    val cardRadius: Float,",
        "    val controlRadius: Float,",
        "    val borderWidth: Float,",
        "    val cardBorder: SkinCardBorder,",
        "    val shadow: SkinShadowTokens,",
        "    val titleDesign: SkinFontDesign,",
        "    val titleWeight: SkinFontWeight,",
        "    val timerDesign: SkinFontDesign,",
        "    val timerWeight: SkinFontWeight,",
        "    val ringStyle: SkinRingStyle,",
        "    val ringWidth: Float,",
        "    val ringKnob: Boolean,",
        "    val ringGlow: Boolean,",
        "    val light: SkinPaletteTokens,",
        "    val dark: SkinPaletteTokens,",
        ")",
        "",
        "object SkinCatalog {",
        "    val layouts: Map<SkinLayout, SkinLayoutTokens> = mapOf(",
    ]
    for name in LAYOUTS:
        l = spec["layouts"][name]
        out.append(f"        SkinLayout.{enum_name(name)} to SkinLayoutTokens({l['pageInset']}f, {l['pageSpacing']}f, "
                   f"{l['cardPadding']}f, {l['rowSpacing']}f),")
    out += ["    )", "", "    /** Picker order. */", "    val all: List<SkinTokens> = listOf("]

    def palette(p: dict) -> str:
        return "SkinPaletteTokens(" + ", ".join(f"0x{p[k].upper()}" for k in COLOR_KEYS) + ")"

    for s in spec["skins"]:
        sh = spec["shadows"][s["shape"]["shadow"]]
        forced = f"SkinForcedScheme.{enum_name(s['forcedScheme'])}" if s["forcedScheme"] else "null"
        out += [
            "        SkinTokens(",
            f"            id = \"{s['id']}\", title = \"{s['title']}\", tagline = \"{s['tagline']}\",",
            f"            layout = SkinLayout.{enum_name(s['layout'])}, forcedScheme = {forced},",
            f"            cardRadius = {s['shape']['cardRadius']}f, controlRadius = {s['shape']['controlRadius']}f, "
            f"borderWidth = {s['shape']['borderWidth']}f, cardBorder = SkinCardBorder.{enum_name(s['shape']['cardBorder'])},",
            f"            shadow = SkinShadowTokens({sh['radius']}f, {sh['x']}f, {sh['y']}f, {sh['opacity']}f, SkinShadowColor.{enum_name(sh['color'])}),",
            f"            titleDesign = SkinFontDesign.{enum_name(s['type']['titleDesign'])}, titleWeight = SkinFontWeight.{enum_name(s['type']['titleWeight'])},",
            f"            timerDesign = SkinFontDesign.{enum_name(s['type']['timerDesign'])}, timerWeight = SkinFontWeight.{enum_name(s['type']['timerWeight'])},",
            f"            ringStyle = SkinRingStyle.{enum_name(s['ring']['style'])}, ringWidth = {s['ring']['width']}f, "
            f"ringKnob = {str(s['ring']['knob']).lower()}, ringGlow = {str(s['ring']['glow']).lower()},",
            f"            light = {palette(s['light'])},",
            f"            dark = {palette(s['dark'])},",
            "        ),",
        ]
    glyphs = spec["pixelGlyphs"]
    out += ["    )", "}", "", "/** 5x7 bitmap digits for the pixel timer; rows top to bottom, '1' = lit cell. */", "object PixelGlyphs {",
            f"    const val HEIGHT = {glyphs['height']}", "    val table: Map<Char, List<String>> = mapOf("]
    for ch, rows in glyphs["glyphs"].items():
        out.append(f"        '{ch}' to listOf(" + ", ".join(f"\"{r}\"" for r in rows) + "),")
    out += ["    )", "}", ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if generated files differ from the spec")
    args = parser.parse_args()
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    errors = validate(spec)
    if errors:
        print("\n".join("ERROR " + e for e in errors))
        return 1
    outputs = {SWIFT_OUT: swift_source(spec), KOTLIN_OUT: kotlin_source(spec)}
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
    if args.check:
        for path in stale:
            print(f"STALE {path.relative_to(ROOT)} (run python3 design/gen_skins.py)")
        if not stale:
            print(f"SKINS OK skins={len(spec['skins'])} contrast_rules={len(CONTRAST_RULES)} generated files current")
        return 1 if stale else 0
    for path in stale:
        path.write_text(outputs[path], encoding="utf-8")
        print(f"WROTE {path.relative_to(ROOT)}")
    print(f"SKINS OK skins={len(spec['skins'])} contrast_rules={len(CONTRAST_RULES)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
